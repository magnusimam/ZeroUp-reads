// Regenerates migrations/0002_seed_books.sql from the frontend's own
// src/utils/mockData.js MOCK_BOOKS array — read directly off that file
// rather than hand-copied, so the seed can never drift out of sync with
// the actual source of truth, and re-running this after mockData.js
// changes (new books, edited content) regenerates a correct migration
// instead of someone hand-editing SQL.
//
// Usage: node backend/scripts/generate-seed-migration.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const mockDataPath = path.join(__dirname, "../../src/utils/mockData.js");
const outputPath = path.join(__dirname, "../migrations/0002_seed_books.sql");

const source = readFileSync(mockDataPath, "utf8");

const match = source.match(/export const MOCK_BOOKS = (\[[\s\S]*?\n\]);/);
if (!match) {
  throw new Error("Could not find `export const MOCK_BOOKS = [...]` in mockData.js");
}

// The array literal is plain data (strings/numbers/booleans/nested
// objects/arrays only, no imports or function calls), so it's safe to
// evaluate directly rather than needing a JS parser dependency.
// eslint-disable-next-line no-new-func
const MOCK_BOOKS = new Function(`return ${match[1]};`)();

function sqlString(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

const lines = [
  "-- Generated by backend/scripts/generate-seed-migration.mjs from",
  "-- src/utils/mockData.js's MOCK_BOOKS — do not hand-edit; re-run the",
  "-- script instead so this can never drift from the frontend's mock data.",
  "",
];

for (const book of MOCK_BOOKS) {
  const attributes = JSON.stringify(book.attributes ?? {});
  lines.push(
    `INSERT INTO books (id, title, author, language, level, total_pages, category, age_group, rating, reads, description, is_educational, attributes) VALUES (${[
      sqlString(book.id),
      sqlString(book.title),
      sqlString(book.author),
      sqlString(book.language),
      sqlString(book.level),
      Number(book.totalPages),
      sqlString(book.category),
      sqlString(book.ageGroup ?? null),
      Number(book.rating ?? 0),
      Number(book.reads ?? 0),
      sqlString(book.description ?? null),
      book.isEducational ? 1 : 0,
      sqlString(attributes),
    ].join(", ")});`
  );

  (book.content ?? []).forEach((pageText, index) => {
    lines.push(
      `INSERT INTO book_pages (book_id, page_number, content) VALUES (${sqlString(book.id)}, ${index + 1}, ${sqlString(pageText)});`
    );
  });
  lines.push("");
}

writeFileSync(outputPath, lines.join("\n"));
console.log(`Wrote ${outputPath} — ${MOCK_BOOKS.length} books.`);
